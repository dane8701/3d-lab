#!/usr/bin/env python3
"""Reconstruct a printable ribbed tumbler from an explicitly estimated profile.

Run from any directory: python models/verre-dane-sama/src/generate.py
The inscription is vector lettering: Dane SAMA / chill with me.
Its polygons are generated by src/generate_text.py; no reference image is needed.
All exported coordinates are millimetres; the bottom rests on Z=0.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from xml.sax.saxutils import escape
import zipfile

import manifold3d as mf
import numpy as np
import trimesh
from shapely.geometry import Polygon, Point
from shapely import affinity, make_valid
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[1]


def log(message):
    print(message, flush=True)


def as_manifold(mesh):
    mesh = mesh.copy()
    mesh.merge_vertices()
    mesh.fix_normals()
    result = mf.Manifold(mf.Mesh64(np.asarray(mesh.vertices, dtype=np.float64),
                                  np.asarray(mesh.faces, dtype=np.uint64)))
    if result.status() != mf.Error.NoError:
        raise ValueError(f"Invalid solid: {result.status()}")
    return result


def as_mesh(solid):
    raw = solid.to_mesh64()
    mesh = trimesh.Trimesh(vertices=np.asarray(raw.vert_properties)[:, :3],
                           faces=np.asarray(raw.tri_verts), process=True)
    mesh.fix_normals()
    return mesh


def printable_mesh(mesh, scale=1.0):
    """Clean faces after STL's actual float32 quantization, not just in CAD."""
    mesh = mesh.copy()
    mesh.apply_scale(scale)
    mesh.vertices = mesh.vertices.astype(np.float32).astype(np.float64)
    mesh.merge_vertices()
    mesh.update_faces(mesh.nondegenerate_faces())
    mesh.update_faces(mesh.unique_faces())
    mesh.remove_unreferenced_vertices()
    mesh.fix_normals()
    if not mesh.is_watertight or not mesh.is_volume:
        raise ValueError("Mesh is not a closed solid at STL coordinate precision")
    return mesh


def reference_radius(z):
    """Valley radius of the approximately conical outer wall, in mm."""
    return 28.9 + 9.7 * np.asarray(z) / 158.0


def smoothstep(v):
    v = np.clip(v, 0.0, 1.0)
    return v * v * (3.0 - 2.0 * v)


def make_cup(p, with_badge=True):
    count = p["angular_segments"]
    theta = np.arange(count) * (2 * np.pi / count)
    profile = [(0.0, 0.0, False), (28.5, 0.0, False),
               (29.0, 0.4, False), (29.2, 1.2, False), (29.0, 2.0, False)]
    # Denser rings where the smooth support for the medallion meets the ribs.
    zs = np.unique(np.concatenate((np.linspace(3, 155.5, 31),
                                   np.arange(77, 135.1, 0.9))))
    for z in zs:
        profile.append((float(reference_radius(z)), float(z), True))
    # A 1.3 mm round lip; the maximum diameter is exactly 80 mm.
    for a in np.linspace(-np.pi / 2, np.pi, 25):
        profile.append((38.7 + 1.3 * np.cos(a), 158.7 + 1.3 * np.sin(a), False))
    wall = p["wall_mm"]
    for z in np.linspace(157.4, 4.0, 16):
        profile.append((float(reference_radius(z) - wall), float(z), False))
    # Rounded inside floor, 3 mm above the flat exterior bottom.
    corner_r = float(reference_radius(4.0) - wall - 1.0)
    for a in np.linspace(0, np.pi / 2, 9)[1:]:
        profile.append((corner_r + np.cos(a), 4.0 - np.sin(a), False))
    profile.append((0.0, 3.0, False))

    vertices, rings = [], []
    for radius, z, ribbed in profile:
        if radius == 0:
            rings.append([len(vertices)])
            vertices.append([0.0, 0.0, z])
            continue
        r = np.full(count, radius)
        if ribbed:
            envelope = smoothstep((z - 3.0) / 3.0) * smoothstep((156.0 - z) / 4.0)
            ribs = p["rib_depth_mm"] * (0.5 + 0.5 * np.cos(p["rib_count"] * theta))
            r += ribs * envelope
            if with_badge:
                # A smooth, fully connected backing under the applied emblem.
                front_x = radius * np.sin(theta)
                distance = np.sqrt(front_x ** 2 + (z - p["badge_center_z_mm"]) ** 2)
                patch = smoothstep((p["badge_radius_mm"] + 0.8 - distance) / 0.8)
                patch *= (np.cos(theta) > 0)
                r = r * (1 - patch) + (radius + p["rib_depth_mm"]) * patch
        first = len(vertices)
        vertices.extend(np.column_stack((r * np.sin(theta), -r * np.cos(theta),
                                         np.full(count, z))).tolist())
        rings.append(np.arange(first, first + count).tolist())

    faces = []
    for previous, current in zip(rings[:-1], rings[1:]):
        for i in range(count):
            j = (i + 1) % count
            if len(previous) == 1:
                faces.append([previous[0], current[j], current[i]])
            elif len(current) == 1:
                faces.append([previous[i], previous[j], current[0]])
            else:
                faces.append([previous[i], previous[j], current[j]])
                faces.append([previous[i], current[j], current[i]])
    mesh = trimesh.Trimesh(vertices=vertices, faces=faces, process=True)
    mesh.fix_normals()
    assert mesh.is_watertight and mesh.is_volume, "Cup profile is not closed"
    return as_manifold(mesh).simplify(p["mesh_tolerance_mm"])


def flat_to_curved(poly, back, front, p):
    """Extrude a planar polygon, then map both surfaces to the conical wall."""
    flat = trimesh.creation.extrude_polygon(poly, height=front - back, engine="earcut")
    flat.vertices[:, 2] += back
    solid = as_manifold(flat).refine_to_length(p["badge_mesh_edge_mm"])

    def warp(points):
        out = np.empty_like(points)
        x = points[:, 0]
        z = points[:, 1] + p["badge_center_z_mm"]
        radius = reference_radius(z) + p["rib_depth_mm"]
        out[:, 0] = x
        out[:, 1] = -np.sqrt(radius * radius - x * x) - points[:, 2]
        out[:, 2] = z
        return out

    return solid.warp_batch(warp).simplify(p["mesh_tolerance_mm"] / 3)


def polygons_from_records(records, radius):
    for record in records:
        polygon = Polygon(record["outer"], record.get("holes", []))
        polygon = affinity.scale(polygon, xfact=radius, yfact=radius, origin=(0, 0))
        polygon = make_valid(polygon)
        items = list(polygon.geoms) if hasattr(polygon, "geoms") else [polygon]
        for item in items:
            if isinstance(item, Polygon) and item.area > 0.015:
                yield item


def make_emblem(data, p):
    circle = Point(0, 0).buffer(p["badge_radius_mm"], quad_segs=96)
    disc = flat_to_curved(circle, -0.25, 0.55, p)
    white_solids, black_solids = [], []
    white_shapes = [polygon.buffer(0.05, join_style="round")
                    for polygon in polygons_from_records(data["white"], p["badge_radius_mm"])]
    # Close sub-pixel gaps so a float32 STL cannot collapse them into pinched edges.
    white_shapes = unary_union(white_shapes).buffer(0.035).buffer(-0.035).intersection(circle.buffer(-0.12))
    white_shapes = white_shapes.geoms if hasattr(white_shapes, "geoms") else [white_shapes]
    for polygon in white_shapes:
        pieces = polygon.geoms if hasattr(polygon, "geoms") else [polygon]
        for piece in pieces:
            if isinstance(piece, Polygon) and piece.area > 0.015:
                white_solids.append(flat_to_curved(piece, 0.35, 0.95, p))
    for polygon in polygons_from_records(data["black"], p["badge_radius_mm"]):
        polygon = polygon.intersection(circle.buffer(-0.12)).buffer(0.025).buffer(-0.025)
        pieces = polygon.geoms if hasattr(polygon, "geoms") else [polygon]
        for piece in pieces:
            if isinstance(piece, Polygon) and piece.area > 0.015:
                black_solids.append(flat_to_curved(piece, 0.35, 0.80, p))
    if not white_solids or not black_solids:
        raise ValueError("The medallion must contain white lettering and black wave geometry")
    white = mf.Manifold.batch_boolean(white_solids, mf.OpType.Add)
    black_full = mf.Manifold.batch_boolean(black_solids, mf.OpType.Add)
    black = black_full - white
    red = disc - white - black
    union = mf.Manifold.batch_boolean([disc, white, black_full], mf.OpType.Add)
    return {"medaillon-rouge": red, "logo-blanc": white, "vague-noire": black}, union


def write_3mf(parts, destination):
    """Core 3MF: one assembled object, four named, coloured, disjoint parts.

    The file contains geometry/materials only, not a sliced print job or a
    printer-specific preset. The slicer may ask the user to assign filaments.
    """
    colours = {"corps": "#CDD5DCFF", "medaillon-rouge": "#E51020FF",
               "logo-blanc": "#FFFFFFFF", "vague-noire": "#151515FF"}
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<model unit="millimeter" xml:lang="fr-FR" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">',
             '<metadata name="Title">Verre cannele Dane SAMA - chill with me</metadata>',
             '<resources><basematerials id="1">']
    for name in parts:
        lines.append(f'<base name="{escape(name)}" displaycolor="{colours[name]}"/>')
    lines.append('</basematerials>')
    for index, (name, mesh) in enumerate(parts.items()):
        lines.append(f'<object id="{index+2}" name="{escape(name)}" type="model" pid="1" pindex="{index}"><mesh><vertices>')
        lines.extend(f'<vertex x="{x:.9g}" y="{y:.9g}" z="{z:.9g}"/>' for x, y, z in mesh.vertices)
        lines.append('</vertices><triangles>')
        lines.extend(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in mesh.faces)
        lines.append('</triangles></mesh></object>')
    assembly_id = len(parts) + 2
    lines.append(f'<object id="{assembly_id}" name="Verre Dane SAMA" type="model"><components>')
    lines.extend(f'<component objectid="{i+2}"/>' for i in range(len(parts)))
    lines.append(f'</components></object></resources><build><item objectid="{assembly_id}"/></build></model>')
    with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        archive.writestr('3D/3dmodel.model', '\n'.join(lines))
        archive.writestr('_rels/.rels', '<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Target="/3D/3dmodel.model" Id="rel0" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/></Relationships>')
        archive.writestr('[Content_Types].xml', '<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/></Types>')


def inspect_mesh(mesh):
    return {"vertices": len(mesh.vertices), "triangles": len(mesh.faces),
            "watertight": bool(mesh.is_watertight),
            "winding_consistent": bool(mesh.is_winding_consistent),
            "positive_volume": bool(mesh.is_volume),
            "volume_mm3": round(float(mesh.volume), 3),
            "bounds_mm": np.round(mesh.bounds, 6).tolist(),
            "components": len(mesh.split(only_watertight=False))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--parameters", type=Path, default=ROOT / "src/parameters.json")
    parser.add_argument("--body-only", action="store_true", help="Generate the unbranded cup only")
    args = parser.parse_args()
    p = json.loads(args.parameters.read_text())
    exports = ROOT / "exports"
    parts_dir = exports / "parts"
    parts_dir.mkdir(parents=True, exist_ok=True)
    scale = p["scale"]

    log("Building hollow cup, ribs, lip and flat base...")
    bare_solid = make_cup(p, with_badge=False)
    bare = printable_mesh(as_mesh(bare_solid), scale)
    bare.export(exports / "verre-sans-logo.stl")
    if args.body_only:
        log(f"Written {exports / 'verre-sans-logo.stl'}")
        return

    logo_data = json.loads((ROOT / "src/logo-contours.json").read_text())
    body = make_cup(p, with_badge=True)
    log("Building curved medallion and personalized lettering...")
    emblem, emblem_union = make_emblem(logo_data, p)
    coloured = {"corps": body - emblem_union, **emblem}
    combined = (body + emblem_union).simplify(0.001)
    if combined.status() != mf.Error.NoError:
        raise ValueError(f"Boolean union failed: {combined.status()}")
    log("Exporting the single solid STL and the multi-part 3MF...")
    union_mesh = printable_mesh(as_mesh(combined), scale)
    union_mesh.export(exports / "verre.stl")
    parts = {}
    for name, solid in coloured.items():
        mesh = printable_mesh(as_mesh(solid.simplify(0.001)), scale)
        parts[name] = mesh
        mesh.export(parts_dir / f"{name}.stl")
    write_3mf(parts, exports / "verre-multicolore.3mf")

    # Validate the actual STL files after serialization, not only the CAD solids.
    log("Checking saved files...")
    report = {"units": "millimeter", "estimated_from_one_photo": True,
              "physical_print_tested": False,
              "inscriptions": logo_data.get("metadata", {}).get("texts", ["Dane SAMA", "chill with me"]),
              "wall_nominal_design_mm": p["wall_mm"] * scale,
              "floor_design_mm": 3.0 * scale,
              "stl": {}, "parts": {}}
    for filename in ["verre.stl", "verre-sans-logo.stl"]:
        mesh = trimesh.load_mesh(exports / filename, process=True)
        result = inspect_mesh(mesh)
        report["stl"][filename] = result
        if not (result["watertight"] and result["winding_consistent"] and result["positive_volume"] and result["components"] == 1):
            raise ValueError(f"Failed validation for {filename}: {result}")
    for name in parts:
        result = inspect_mesh(trimesh.load_mesh(parts_dir / f"{name}.stl", process=True))
        report["parts"][name] = result
        if not (result["watertight"] and result["winding_consistent"] and result["positive_volume"]):
            raise ValueError(f"Failed validation for part {name}: {result}")
    scene = trimesh.load(exports / "verre-multicolore.3mf", force="scene")
    report["three_mf"] = {"mesh_count": len(scene.geometry), "bounds_mm": np.round(scene.bounds, 6).tolist()}
    assert len(scene.geometry) == 4
    assert all(m.is_watertight and m.is_volume for m in scene.geometry.values())
    report["partition_volume_difference_mm3"] = round(abs(sum(m.volume for m in parts.values()) - union_mesh.volume), 6)
    if report["partition_volume_difference_mm3"] > 0.02:
        raise ValueError("The material parts do not match the unified solid")
    (exports / "validation.json").write_text(json.dumps(report, indent=2) + "\n")
    log(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
